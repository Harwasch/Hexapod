// The small bridge IDL is authoritative. No generator dependency or network needed.
import { format } from "prettier";
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const root = new URL("../../../", import.meta.url);
const schema = JSON.parse(
  readFileSync(new URL("apps/ios/Modules/Globe/Bridge/schema.json", root), "utf8"),
);
const swiftType = (type) =>
  type.endsWith("?")
    ? `${swiftType(type.slice(0, -1))}?`
    : type.endsWith("[]")
      ? `[${swiftType(type.slice(0, -2))}]`
      : type;
const tsType = (type) =>
  type.endsWith("?")
    ? `${tsType(type.slice(0, -1))} | null`
    : type.endsWith("[]")
      ? `${tsType(type.slice(0, -2))}[]`
      : ({ String: "string", Double: "number" }[type] ?? type);
const fields = (record) => Object.entries(record);
let ts = "// Generated by scripts/generate-globe-bridge.mjs; edit Bridge/schema.json.\n";
let swift =
  "// Generated by scripts/generate-globe-bridge.mjs; edit Bridge/schema.json.\nimport Foundation\n";
for (const [name, record] of fields(schema.records)) {
  ts += `export interface ${name} {\n${fields(record)
    .map(([k, t]) => `${k}: ${tsType(t)};`)
    .join("\n")}\n}\n`;
  swift += `public struct ${name}: Codable, Equatable, Sendable {\n${fields(record)
    .map(([k, t]) => `public let ${k}: ${swiftType(t)}`)
    .join("\n")}\npublic init(${fields(record)
    .map(([k, t]) => `${k}: ${swiftType(t)}`)
    .join(", ")}) {\n${fields(record)
    .map(([k]) => `self.${k} = ${k}`)
    .join(
      "\n",
    )}\n}\nprivate enum CodingKeys: String, CodingKey {case ${Object.keys(record).join(", ")}}\npublic func encode(to encoder: any Encoder) throws {\nvar c = encoder.container(keyedBy: CodingKeys.self)\n${Object.keys(
    record,
  )
    .map((k) => `try c.encode(${k}, forKey: .${k})`)
    .join("\n")}\n}\n}\n`;
}
ts +=
  "export type BridgeMessage =\n" +
  fields(schema.messages)
    .map(
      ([name, record]) =>
        `| {version: ${schema.version}; type: "${name}"; ${fields(record)
          .map(([k, t]) => `${k}: ${tsType(t)};`)
          .join(" ")}}`,
    )
    .join("\n") +
  ";\n";
swift +=
  "public enum BridgeMessage: Codable, Equatable, Sendable {\n" +
  fields(schema.messages)
    .map(
      ([name, r]) =>
        `case ${name}${
          fields(r).length
            ? `(${fields(r)
                .map(([k, t]) => `${k}: ${swiftType(t)}`)
                .join(", ")})`
            : ""
        }`,
    )
    .join("\n");
const keys = [
  ...new Set(["version", "type", ...Object.values(schema.messages).flatMap((r) => Object.keys(r))]),
];
swift += `\nprivate enum CodingKeys: String, CodingKey {case ${keys.join(", ")}}\npublic init(from decoder: any Decoder) throws {\nlet c = try decoder.container(keyedBy: CodingKeys.self)\nguard try c.decode(Int.self, forKey: .version) == ${schema.version} else {throw GlobeError.invalidResponse}\nswitch try c.decode(String.self, forKey: .type) {\n`;
for (const [name, r] of fields(schema.messages))
  swift += `case "${name}": self = .${name}${
    fields(r).length
      ? `(${fields(r)
          .map(([k, t]) => `${k}: try c.decode(${swiftType(t)}.self, forKey: .${k})`)
          .join(", ")})`
      : ""
  }\n`;
swift +=
  "default: throw GlobeError.invalidResponse\n}\n}\npublic func encode(to encoder: any Encoder) throws {\nvar c = encoder.container(keyedBy: CodingKeys.self)\ntry c.encode(1, forKey: .version)\nswitch self {\n";
for (const [name, r] of fields(schema.messages)) {
  swift += `case ${fields(r).length ? "let " : ""}.${name}${fields(r).length ? `(${Object.keys(r).join(", ")})` : ""}:\ntry c.encode("${name}", forKey: .type)\n${Object.keys(
    r,
  )
    .map((k) => `try c.encode(${k}, forKey: .${k})`)
    .join("\n")}\n`;
}
swift += "}\n}\n}\n";
ts = await format(ts, { parser: "typescript" });
for (const [path, content] of [
  ["apps/web/src/globe-embed/generated.ts", ts],
  ["apps/ios/Modules/Globe/Sources/Globe/BridgeGenerated.swift", swift],
]) {
  const url = new URL(path, root);
  if (process.argv.includes("--check")) {
    // Whitespace is formatter-owned; token content is generator-owned.
    if (readFileSync(url, "utf8").replace(/\s/g, "") !== content.replace(/\s/g, ""))
      throw Error(`Stale generated bridge: ${fileURLToPath(url)}`);
  } else writeFileSync(url, content);
}
